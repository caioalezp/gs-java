CREATE TABLE T_CT_REGIAO (
    ID_REGIAO NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_REGIAO VARCHAR2(100) NOT NULL,
    NM_CIDADE VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_CT_REGIAO PRIMARY KEY (ID_REGIAO)
);

CREATE TABLE T_CT_MICRO_REGIAO (
    ID_MICRO_REGIAO NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_MICRO_REGIAO VARCHAR2(150) NOT NULL,
    VL_LATITUDE NUMBER(9,6) NOT NULL,
    VL_LONGITUDE NUMBER(9,6) NOT NULL,
    NR_CAPACIDADE_ESCOAMENTO NUMBER(3) NOT NULL,
    ID_REGIAO NUMBER NOT NULL,
    CONSTRAINT PK_CT_MICRO PRIMARY KEY (ID_MICRO_REGIAO),
    CONSTRAINT CK_CT_MICRO_ESCOAMENTO CHECK (NR_CAPACIDADE_ESCOAMENTO BETWEEN 0 AND 100),
    CONSTRAINT CK_CT_MICRO_LAT CHECK (VL_LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_CT_MICRO_LON CHECK (VL_LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT FK_CT_MICRO_REGIAO FOREIGN KEY (ID_REGIAO) REFERENCES T_CT_REGIAO (ID_REGIAO)
);

CREATE TABLE T_CT_SENSOR (
    ID_SENSOR NUMBER GENERATED ALWAYS AS IDENTITY,
    CD_SENSOR VARCHAR2(50) NOT NULL,
    TP_SENSOR VARCHAR2(20) NOT NULL,
    ST_SENSOR VARCHAR2(20) NOT NULL,
    ID_MICRO_REGIAO NUMBER NOT NULL,
    CONSTRAINT PK_CT_SENSOR PRIMARY KEY (ID_SENSOR),
    CONSTRAINT UK_CT_SENSOR_SENSOR UNIQUE (CD_SENSOR),
    CONSTRAINT CK_CT_SENSOR_TP CHECK (TP_SENSOR IN ('CHUVA', 'NIVEL_AGUA', 'VIA')),
    CONSTRAINT CK_CT_SENSOR_ST CHECK (ST_SENSOR IN ('ATIVO', 'INATIVO', 'MANUTENCAO')),
    CONSTRAINT FK_CT_SENSOR_MICRO FOREIGN KEY (ID_MICRO_REGIAO) REFERENCES T_CT_MICRO_REGIAO (ID_MICRO_REGIAO)
);

CREATE TABLE T_CT_LEITURA_SENSOR (
    ID_LEITURA NUMBER GENERATED ALWAYS AS IDENTITY,
    VL_LEITURA NUMBER(10,2) NOT NULL,
    DS_UNIDADE VARCHAR2(20) NOT NULL,
    DT_LEITURA TIMESTAMP NOT NULL,
    ID_SENSOR NUMBER NOT NULL,
    CONSTRAINT PK_CT_LEITURA PRIMARY KEY (ID_LEITURA),
    CONSTRAINT CK_CT_LEITURA_VALOR CHECK (VL_LEITURA >= 0),
    CONSTRAINT FK_CT_LEITURA_SENSOR FOREIGN KEY (ID_SENSOR) REFERENCES T_CT_SENSOR (ID_SENSOR)
);

CREATE TABLE T_CT_MORADOR (
    ID_MORADOR NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_MORADOR VARCHAR2(120) NOT NULL,
    DS_EMAIL VARCHAR2(150) NOT NULL,
    NR_TELEFONE VARCHAR2(20),
    ID_MICRO_REGIAO NUMBER NOT NULL,
    CONSTRAINT PK_CT_MORADOR PRIMARY KEY (ID_MORADOR),
    CONSTRAINT UK_CT_MORADOR_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT FK_CT_MORADOR_MICRO FOREIGN KEY (ID_MICRO_REGIAO) REFERENCES T_CT_MICRO_REGIAO (ID_MICRO_REGIAO)
);

CREATE TABLE T_CT_RELATO (
    ID_RELATO NUMBER GENERATED ALWAYS AS IDENTITY,
    TP_RELATO VARCHAR2(20) NOT NULL,
    DS_RELATO VARCHAR2(500) NOT NULL,
    DT_RELATO TIMESTAMP NOT NULL,
    ST_RELATO VARCHAR2(20) NOT NULL,
    ID_MORADOR NUMBER NOT NULL,
    ID_MICRO_REGIAO NUMBER NOT NULL,
    CONSTRAINT PK_CT_RELATO PRIMARY KEY (ID_RELATO),
    CONSTRAINT CK_CT_RELATO_TP CHECK (TP_RELATO IN ('ALAGAMENTO', 'BUEIRO_ENTUPIDO', 'VIA_BLOQUEADA', 'QUEDA_ARVORE', 'OUTRO')),
    CONSTRAINT CK_CT_RELATO_ST CHECK (ST_RELATO IN ('PENDENTE', 'VALIDADO', 'DESCARTADO')),
    CONSTRAINT FK_CT_RELATO_MORADOR FOREIGN KEY (ID_MORADOR) REFERENCES T_CT_MORADOR (ID_MORADOR),
    CONSTRAINT FK_CT_RELATO_MICRO FOREIGN KEY (ID_MICRO_REGIAO) REFERENCES T_CT_MICRO_REGIAO (ID_MICRO_REGIAO)
);

CREATE TABLE T_CT_HISTORICO_ALAGAMENTO (
    ID_HISTORICO NUMBER GENERATED ALWAYS AS IDENTITY,
    DT_OCORRENCIA DATE NOT NULL,
    NR_GRAVIDADE NUMBER(1) NOT NULL,
    NR_DURACAO_MIN NUMBER(6) NOT NULL,
    ID_MICRO_REGIAO NUMBER NOT NULL,
    CONSTRAINT PK_CT_HIST_ALAG PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT CK_CT_HIST_GRAVIDADE CHECK (NR_GRAVIDADE BETWEEN 1 AND 5),
    CONSTRAINT CK_CT_HIST_DURACAO CHECK (NR_DURACAO_MIN > 0),
    CONSTRAINT FK_CT_HIST_ALAG_MICRO FOREIGN KEY (ID_MICRO_REGIAO) REFERENCES T_CT_MICRO_REGIAO (ID_MICRO_REGIAO)
);

CREATE TABLE T_CT_ALERTA (
    ID_ALERTA NUMBER GENERATED ALWAYS AS IDENTITY,
    NV_RISCO VARCHAR2(20) NOT NULL,
    VL_PROBABILIDADE NUMBER(5,2) NOT NULL,
    VL_CONFIANCA NUMBER(5,2) NOT NULL,
    DS_MENSAGEM VARCHAR2(400) NOT NULL,
    DS_ROTA_ALTERNATIVA VARCHAR2(300),
    DT_GERACAO TIMESTAMP NOT NULL,
    ST_ALERTA VARCHAR2(20) NOT NULL,
    ID_MICRO_REGIAO NUMBER NOT NULL,
    CONSTRAINT PK_CT_ALERTA PRIMARY KEY (ID_ALERTA),
    CONSTRAINT CK_CT_ALERTA_NV CHECK (NV_RISCO IN ('BAIXO', 'MODERADO', 'ALTO', 'CRITICO')),
    CONSTRAINT CK_CT_ALERTA_ST CHECK (ST_ALERTA IN ('ATIVO', 'EM_ATENDIMENTO', 'ENCERRADO')),
    CONSTRAINT CK_CT_ALERTA_PROB CHECK (VL_PROBABILIDADE BETWEEN 0 AND 100),
    CONSTRAINT CK_CT_ALERTA_CONF CHECK (VL_CONFIANCA BETWEEN 0 AND 100),
    CONSTRAINT FK_CT_ALERTA_MICRO FOREIGN KEY (ID_MICRO_REGIAO) REFERENCES T_CT_MICRO_REGIAO (ID_MICRO_REGIAO)
);

CREATE TABLE T_CT_EQUIPE_ATENDIMENTO (
    ID_EQUIPE NUMBER GENERATED ALWAYS AS IDENTITY,
    NM_EQUIPE VARCHAR2(100) NOT NULL,
    DS_ESPECIALIDADE VARCHAR2(100) NOT NULL,
    ST_DISPONIBILIDADE VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_CT_EQUIPE PRIMARY KEY (ID_EQUIPE),
    CONSTRAINT CK_CT_EQUIPE_ST CHECK (ST_DISPONIBILIDADE IN ('DISPONIVEL', 'OCUPADA'))
);

CREATE TABLE T_CT_ATENDIMENTO (
    ID_ALERTA NUMBER NOT NULL,
    ID_EQUIPE NUMBER NOT NULL,
    CONSTRAINT PK_CT_ATENDIMENTO PRIMARY KEY (ID_ALERTA, ID_EQUIPE),
    CONSTRAINT FK_CT_ATEND_ALERTA FOREIGN KEY (ID_ALERTA) REFERENCES T_CT_ALERTA (ID_ALERTA),
    CONSTRAINT FK_CT_ATEND_EQUIPE FOREIGN KEY (ID_EQUIPE) REFERENCES T_CT_EQUIPE_ATENDIMENTO (ID_EQUIPE)
);

-- Índices para as consultas do cálculo de risco
CREATE INDEX IDX_CT_LEITURA_SENSOR_DT ON T_CT_LEITURA_SENSOR (ID_SENSOR, DT_LEITURA);
CREATE INDEX IDX_CT_RELATO_MICRO_DT ON T_CT_RELATO (ID_MICRO_REGIAO, DT_RELATO);
CREATE INDEX IDX_CT_ALERTA_MICRO_DT ON T_CT_ALERTA (ID_MICRO_REGIAO, DT_GERACAO);
CREATE INDEX IDX_CT_HIST_MICRO ON T_CT_HISTORICO_ALAGAMENTO (ID_MICRO_REGIAO);
CREATE INDEX IDX_CT_SENSOR_MICRO ON T_CT_SENSOR (ID_MICRO_REGIAO);
CREATE INDEX IDX_CT_MORADOR_MICRO ON T_CT_MORADOR (ID_MICRO_REGIAO);
CREATE INDEX IDX_CT_MICRO_REGIAO ON T_CT_MICRO_REGIAO (ID_REGIAO);
